from collections.abc import Callable
from pathlib import Path
import unicodedata

import regex


PINNED_UNICODE_VERSION = "16.0.0"
MAX_CODE_POINT = 0x110000
OUTPUT_PATH = Path(__file__).parents[1] / "src" / "terminal_browser" / "core" / "text.py"


if unicodedata.unidata_version != PINNED_UNICODE_VERSION:
    raise RuntimeError(
        f"expected Unicode {PINNED_UNICODE_VERSION}, got {unicodedata.unidata_version}"
    )


def compact_ranges(
    predicate: Callable[[int], bool],
) -> tuple[tuple[int, int], ...]:
    ranges: list[tuple[int, int]] = []
    range_start: int | None = None
    previous: int | None = None
    for codepoint in range(MAX_CODE_POINT):
        matches = predicate(codepoint)
        if matches and range_start is None:
            range_start = codepoint
        if matches and previous is not None and codepoint == previous + 1:
            previous = codepoint
            continue
        if range_start is not None and previous is not None:
            ranges.append((range_start, previous))
        if matches:
            range_start = codepoint
            previous = codepoint
        else:
            range_start = None
            previous = None
    if range_start is not None and previous is not None:
        ranges.append((range_start, previous))
    return tuple(ranges)


def category_is(category: str) -> Callable[[int], bool]:
    return lambda codepoint: unicodedata.category(chr(codepoint)) == category


def east_asian_width_is(width: str) -> Callable[[int], bool]:
    return lambda codepoint: unicodedata.east_asian_width(chr(codepoint)) == width


def regex_property_is(property_name: str) -> Callable[[int], bool]:
    pattern = regex.compile(rf"\p{{{property_name}}}")
    return lambda codepoint: pattern.fullmatch(chr(codepoint)) is not None


def format_ranges(name: str, ranges: tuple[tuple[int, int], ...]) -> str:
    values = ", ".join(f"(0x{start:X}, 0x{end:X})" for start, end in ranges)
    return f"{name} = ({values},)\n"


def main() -> None:
    combining = compact_ranges(
        lambda codepoint: unicodedata.category(chr(codepoint)) in {"Mn", "Me"}
    )
    wide = compact_ranges(
        lambda codepoint: unicodedata.east_asian_width(chr(codepoint)) in {"W", "F"}
    )
    variation = compact_ranges(regex_property_is("Variation_Selector"))
    emoji = compact_ranges(regex_property_is("Emoji_Presentation"))
    emoji_modifier = compact_ranges(regex_property_is("Emoji_Modifier"))
    format_control = compact_ranges(category_is("Cf"))

    output = "# Unicode data pinned to version 16.0.0; generated by tools/generate_text_tables.py.\n\n"
    output += "UnicodeRange = tuple[tuple[int, int], ...]\n"
    output += "UNICODE_VERSION = \"16.0.0\"\n"
    output += format_ranges("COMBINING_RANGES", combining)
    output += format_ranges("EAST_ASIAN_WIDE_RANGES", wide)
    output += format_ranges("VARIATION_SELECTOR_RANGES", variation)
    output += format_ranges("EMOJI_PRESENTATION_RANGES", emoji)
    output += format_ranges("EMOJI_MODIFIER_RANGES", emoji_modifier)
    output += format_ranges("FORMAT_CONTROL_RANGES", format_control)
    output += '''

def _in_ranges(codepoint: int, ranges: UnicodeRange) -> bool:
    lower = 0
    upper = len(ranges)
    while lower < upper:
        middle = (lower + upper) // 2
        start, end = ranges[middle]
        if codepoint < start:
            upper = middle
        elif codepoint > end:
            lower = middle + 1
        else:
            return True
    return False


def _scalar_width(character: str) -> int:
    codepoint = ord(character)
    if _in_ranges(codepoint, COMBINING_RANGES):
        return 0
    if _in_ranges(codepoint, VARIATION_SELECTOR_RANGES):
        return 0
    if _in_ranges(codepoint, EMOJI_MODIFIER_RANGES):
        return 0
    if _in_ranges(codepoint, FORMAT_CONTROL_RANGES):
        return 0
    if 0x1F1E6 <= codepoint <= 0x1F1FF:
        return 2
    if _in_ranges(codepoint, EAST_ASIAN_WIDE_RANGES):
        return 2
    if _in_ranges(codepoint, EMOJI_PRESENTATION_RANGES):
        return 2
    return 1


def display_width(text: str) -> int:
    return sum(_scalar_width(character) for character in text)
'''
    OUTPUT_PATH.write_text(output, encoding="utf-8")


if __name__ == "__main__":
    main()
